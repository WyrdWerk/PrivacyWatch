#!/usr/bin/env node
// Generates docs/source-coverage-audit.md from providers.json.
// Flags rows whose notes mention a different URL than sourceUrl (possible
// secondary/primary source divergence) so research cycles can complete verdicts.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'providers.json'), 'utf-8'));
const providers = data.providers || [];

const urlLike = /https?:\/\/[^\s)>"']+/g;
const rows = providers.map((p) => {
  const noteUrls = (p.notes?.match(urlLike) ?? []).filter((u) => !u.startsWith(p.sourceUrl));
  const flagged = noteUrls.length > 0;
  return { p, noteUrls, flagged };
});

const lines = [
  '# Source coverage audit',
  '',
  `Generated by \`scripts/generate-source-audit.mjs\` from providers.json v${data.meta?.version ?? '?'} on ${new Date().toISOString().slice(0, 10)}.`,
  '',
  'A single `sourceUrl` does not automatically evidence every field in a row.',
  'Each row needs a verdict from a research cycle: **sufficient** (one page covers',
  'training/retention/ZDR/location claims) or **split** (add a `sources: [{url, covers}]`',
  'array to providers.json for the rows that need it).',
  '',
  '| Provider | Surface | sourceUrl | Verdict | Notes |',
  '|---|---|---|---|---|',
  ...rows.map(
    ({ p, noteUrls, flagged }) =>
      `| ${p.id} | ${p.surface} | ${p.sourceUrl} | ⏳ pending | ${flagged ? `⚠ notes mention: ${noteUrls.join(', ')}` : ''} |`
  ),
  '',
  `**Status:** 0/${rows.length} verdicts recorded. Flagged rows: ${rows.filter((r) => r.flagged).length}.`,
];

fs.writeFileSync(path.join(root, 'docs', 'source-coverage-audit.md'), lines.join('\n') + '\n');
console.log(`Wrote docs/source-coverage-audit.md (${rows.length} rows, ${rows.filter((r) => r.flagged).length} flagged)`);
